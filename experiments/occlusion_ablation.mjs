// Reproducible occlusion ablation: three trackers on identical detections, N seeds x T seconds per scenario.
// Proportions get Wilson 95% intervals; per-run metrics get mean ± 1.96·SE. Writes experiments/results.md.
//   node experiments/occlusion_ablation.mjs [seeds=20] [seconds=300]
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { MotSession } from '../src/mot/session.js';
import { MOT_SCENARIOS } from '../src/mot/world.js';

const N = +(process.argv[2] || 20), SECS = +(process.argv[3] || 300);
const wilson = (k, n) => { if (!n) return [NaN, NaN]; const z = 1.96, p = k / n, d = 1 + z * z / n, c = (p + z * z / (2 * n)) / d, h = (z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / d; return [Math.max(0, c - h), Math.min(1, c + h)]; };
const ci = (x) => { const m = x.reduce((a, b) => a + b, 0) / x.length, s = Math.sqrt(x.reduce((a, b) => a + (b - m) ** 2, 0) / Math.max(1, x.length - 1)); return `${m.toFixed(2)} ± ${((1.96 * s) / Math.sqrt(x.length)).toFixed(2)}`; };
const pct = (k, n) => { const [lo, hi] = wilson(k, n); return n ? `**${Math.round((100 * k) / n)}%** [${Math.round(100 * lo)}–${Math.round(100 * hi)}] (n=${n})` : '–'; };
let rev = 'unknown'; try { rev = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch {}

let md = `# Occlusion ablation results\n\nGenerated by \`node experiments/occlusion_ablation.mjs ${N} ${SECS}\` at commit \`${rev}\`. ${N} seeds × ${SECS} s per scenario; all trackers see identical detections. Brackets: Wilson 95% interval. ± : 1.96 × standard error over seeds.\n`;
for (const sc of Object.keys(MOT_SCENARIOS)) {
  const acc = {};
  for (let seed = 1; seed <= N; seed++) for (const o of new MotSession({ scenario: sc, seed }).run(SECS).summaries()) {
    const a = (acc[o.name] ||= { s: [0, 0], l: [0, 0], idsw: [], idf1: [], mota: [], gospa: [] });
    o.occByDuration.forEach((b, i) => { const t = i < 2 ? a.s : a.l; t[0] += b.kept; t[1] += b.n; });
    a.idsw.push(o.idsw); a.idf1.push(o.idf1); a.mota.push(o.mota); a.gospa.push(o.gospa);
  }
  md += `\n## ${MOT_SCENARIOS[sc].label}\n\n| tracker | ID kept, occlusion 1–5 s | ID kept, occlusion ≥ 5 s | ID switches / run | IDF1 | MOTA | GOSPA |\n|---|---|---|---|---|---|---|\n`;
  for (const [n, a] of Object.entries(acc)) md += `| ${n} | ${pct(...a.s)} | ${pct(...a.l)} | ${ci(a.idsw)} | ${ci(a.idf1)} | ${ci(a.mota)} | ${ci(a.gospa)} |\n`;
  process.stdout.write('.');
}
writeFileSync(new URL('./results.md', import.meta.url), md);
console.log('\n' + md);
