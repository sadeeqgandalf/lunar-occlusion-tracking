// Step 1 of cars in the lab: how well do the WALKER trackers (constant-velocity EKF, tuned for people) keep a
// driving vehicle's identity? Same trackers, same detections; scores split by what the target is.
//   node experiments/vehicle_baseline.mjs [seeds=20] [seconds=300]
import { writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { MotSession } from '../src/mot/session.js';

const N = +(process.argv[2] || 20), SECS = +(process.argv[3] || 300);
const wilson = (k, n) => { if (!n) return [NaN, NaN]; const z = 1.96, p = k / n, d = 1 + z * z / n, c = (p + z * z / (2 * n)) / d, h = (z * Math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))) / d; return [Math.max(0, c - h), Math.min(1, c + h)]; };
const pct = (k, n) => { const [lo, hi] = wilson(k, n); return n ? `**${Math.round((100 * k) / n)}%** [${Math.round(100 * lo)}–${Math.round(100 * hi)}] (n=${n})` : '–'; };
let rev = 'unknown'; try { rev = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch {}

const acc = {};
for (let seed = 1; seed <= N; seed++) {
  const s = new MotSession({ scenario: 'ltv', seed }).run(SECS);
  const kind = Object.fromEntries(s.world.targets.map((t) => [t.id, t.kind || 'person']));
  const count = (k) => s.world.targets.filter((t) => (t.kind || 'person') === k).length;
  s.runs.forEach((r) => {
    const a = (acc[r.tracker.name] ||= { person: { kept: 0, n: 0, sw: 0, n0: 0 }, vehicle: { kept: 0, n: 0, sw: 0, n0: 0 } });
    for (const e of r.metrics.events) if (e.dur < 5) { const b = a[kind[e.target]]; b.n++; if (e.kept) b.kept++; }
    for (const [id, c] of Object.entries(r.metrics.idswBy)) a[kind[id]].sw += c;
    for (const k of ['person', 'vehicle']) a[k].n0 += count(k);
  });
  process.stdout.write('.');
}
const perMin = (b) => (b.sw / b.n0 / (SECS / 60)).toFixed(2);
let md = `# Vehicle baseline: walker trackers on a driving vehicle\n\nGenerated by \`node experiments/vehicle_baseline.mjs ${N} ${SECS}\` at commit \`${rev}\` (plus uncommitted changes if any). Scenario: Artemis EVA · Lunar Terrain Vehicle (4 astronauts, 2 vehicles at 2–3.5 m/s, minimum turn radius 4 m). ${N} seeds × ${SECS} s. Every tracker uses the constant-velocity EKF tuned for walkers. Brackets: Wilson 95% interval.\n\n| tracker | ID kept, 1–5 s hide: people | ID kept, 1–5 s hide: vehicles | ID switches per target per minute: people | ID switches per target per minute: vehicles |\n|---|---|---|---|---|\n`;
for (const [n, a] of Object.entries(acc)) md += `| ${n} | ${pct(a.person.kept, a.person.n)} | ${pct(a.vehicle.kept, a.vehicle.n)} | ${perMin(a.person)} | ${perMin(a.vehicle)} |\n`;
writeFileSync(new URL('./vehicle_baseline.md', import.meta.url), md);
console.log('\n' + md);
